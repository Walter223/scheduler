import {readFileSync,mkdirSync} from 'node:fs'
import {test,expect} from './helpers/signup-test'
import {AdminPage} from './pages/AdminPage'
const {users,run_id}=JSON.parse(readFileSync(process.env.BFF_E2E_FIXTURE!,'utf8'))
test('authenticated Owner creates an independent company without leaving signup before confirmation',async({page})=>{
 const admin=new AdminPage(page)
 await admin.login(users.find((u:{kind:string})=>u.kind==='golden_owner'))
 await expect(page.getByText('Signed in as E2E',{exact:true})).toBeVisible()
 const before=await (await page.request.get('/api/admin/context')).json()
 await page.goto('/platform')
 await page.getByRole('link',{name:'Create a Business',exact:true}).click()
 await page.getByRole('button',{name:'I already have an account'}).click()
 await page.getByLabel('Business name',{exact:true}).fill('Golden Independent Studio')
 await page.getByLabel('Booking website address',{exact:true}).fill(`${run_id}-golden`)
 await page.getByLabel('Shop name',{exact:true}).fill('Golden Initial Shop')
 await page.getByRole('combobox',{name:'Shop timezone'}).fill('America/Denver')
 await page.getByRole('button',{name:'Review business'}).click()
 await page.getByRole('button',{name:'Create business',exact:true}).click()
 await expect(page.getByText('Golden Independent Studio',{exact:true})).toBeVisible()
 await expect(page.getByText('Your business is ready')).toBeVisible()
 await expect(page).toHaveURL(/\/signup$/)
 mkdirSync('/private/tmp/magnum-signup',{recursive:true})
 await page.screenshot({path:'/private/tmp/magnum-signup/golden-existing-success.png',fullPage:true})
 await page.reload();await expect(page.getByText('Your business is ready')).toBeVisible()
 await page.getByRole('link',{name:'Sign in to Magnum',exact:true}).click()
 await expect(page.getByText('Signed in as E2E',{exact:true})).toBeVisible()
 const after=await (await page.request.get('/api/admin/context')).json()
 expect(after.businesses).toHaveLength(before.businesses.length+1)
 for(const business of before.businesses)expect(after.businesses).toContainEqual(business)
 const created=after.businesses.find((b:{name:string})=>b.name==='Golden Independent Studio')
 expect(created.capabilities).toContain('access')
 await admin.business.selectOption(String(created.id))
 await page.goto(`/setup/${created.id}`)
 await page.getByRole('button',{name:'Begin setup',exact:true}).click()
 await expect(page.getByRole('region',{name:'Business setup'}).getByRole('button',{name:'Configure Golden Initial Shop',exact:true})).toBeVisible()
 await page.screenshot({path:'/private/tmp/magnum-signup/golden-existing-setup.png',fullPage:true})
 await page.goto('/admin');await admin.logout()
})
