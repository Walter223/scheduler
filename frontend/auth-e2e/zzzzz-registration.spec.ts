import {readFileSync,mkdirSync} from 'node:fs'
import {execFileSync} from 'node:child_process'
import {test,expect} from './helpers/signup-test'
const {users,run_id}=JSON.parse(readFileSync(process.env.BFF_E2E_FIXTURE!,'utf8'))
test('fresh browser registration stays in Keycloak; verified pending signup creates its own tenant',async({page})=>{
 const identity=users.find((u:{kind:string})=>u.kind==='registration')
 await page.goto('/platform');await page.getByRole('link',{name:'Create a Business',exact:true}).click()
 mkdirSync('/private/tmp/magnum-signup',{recursive:true})
 await expect(page.getByRole('alert')).toHaveCount(0)
 await page.screenshot({path:'/private/tmp/magnum-signup/signup-account-choices.png',fullPage:true})
 await page.getByRole('button',{name:'Create an account'}).click()
 await expect(page).toHaveURL(/auth\.magnum\.test/)
 mkdirSync('/private/tmp/magnum-signup',{recursive:true})
 for(const width of [1440,390]){await page.setViewportSize({width,height:1000});await page.screenshot({path:`/private/tmp/magnum-signup/keycloak-registration-entry-${width}.png`,fullPage:true})}
 await page.getByLabel('First name',{exact:false}).fill('E2E')
 await page.getByLabel('Last name',{exact:false}).fill('Registration')
 await page.getByLabel('Email',{exact:false}).fill(identity.email)
 await page.getByRole('button',{name:'Register',exact:true}).click()
 await expect(page.getByText(/verify your email|email verification|verification link/i).first()).toBeVisible()
 await page.screenshot({path:'/private/tmp/magnum-signup/keycloak-email-verification.png',fullPage:true})
 expect(await page.context().cookies('http://localhost:5174')).not.toEqual(expect.arrayContaining([expect.objectContaining({name:'magnum_onboarding_dev'})]))
 // Read only the exact disposable recipient from local Mailpit; follow the real one-time email action in Keycloak.
 execFileSync('python3',['../scripts/auth_registration_fixture.py'],{env:process.env,stdio:'pipe'})
 await page.goto(JSON.parse(readFileSync(process.env.BFF_E2E_FIXTURE!,'utf8')).registration_verification_url)
 await page.getByLabel('New Password',{exact:true}).fill(identity.password)
 await page.getByLabel(/confirm password/i).fill(identity.password)
 await page.getByRole('button',{name:/submit|save|continue/i}).click()
 await page.getByLabel('Business name',{exact:true}).fill('Registered Fictional Studio')
 await page.getByLabel('Booking website address',{exact:true}).fill(`${run_id}-registration`)
 await page.getByLabel('Shop name',{exact:true}).fill('Initial shop')
 await page.getByRole('combobox',{name:'Shop timezone'}).fill('America/Denver')
 const help=page.getByLabel('Help: Booking website address',{exact:true})
 await help.focus();await page.keyboard.press('Enter')
 await expect(page.getByRole('note')).toBeVisible();await page.keyboard.press('Escape')
 await help.click();await expect(page.getByRole('note')).toBeVisible();await page.keyboard.press('Escape')
 await page.getByRole('button',{name:'Review business'}).click()
 await page.getByRole('button',{name:'Create business',exact:true}).click()
 await expect(page.getByText('Your business is ready')).toBeVisible()
 await expect(page).toHaveURL(/\/signup$/)
 await page.screenshot({path:'/private/tmp/magnum-signup/golden-new-success.png',fullPage:true})
 await page.reload();await expect(page.getByText('Registered Fictional Studio',{exact:true})).toBeVisible()
 await page.getByRole('link',{name:'Sign in to Magnum',exact:true}).click()
 await expect(page.getByText('Signed in as E2E',{exact:true})).toBeVisible()
 const names=await page.evaluate(async()=>((await (await fetch('/api/admin/context')).json()).businesses as {name:string}[]).map(b=>b.name))
 expect(names).toEqual(['Registered Fictional Studio'])
 const businesses=await page.evaluate(async()=>((await (await fetch('/api/admin/context')).json()).businesses))
 await page.goto(`/setup/${businesses[0].id}`)
 await page.getByRole('button',{name:'Begin setup',exact:true}).click()
 await expect(page.getByRole('region',{name:'Business setup'}).getByRole('button',{name:'Configure Initial shop',exact:true})).toBeVisible()
 await page.screenshot({path:'/private/tmp/magnum-signup/golden-new-setup.png',fullPage:true})
 await page.goto('/admin')
 await page.getByRole('button',{name:'Sign out',exact:true}).click()
})
