for (const kind of ['owner', 'manager']) {
  test(`real ${kind} terminates and rehires a retained employee without restoring access or history`, async ({ page }) => {
    const admin = new AdminPage(page)
    await admin.login(users.find(u => u.kind === kind)!)
    await admin.openEmployees()
    const name = `Created ${kind} Edited`
    await admin.employees.getByRole('button', { name: `View profile and history for ${name}` }).click()
    const profile = page.getByRole('region', { name: 'Employee profile and employment history' })
    const before = (await profile.getByText(/Stable employee #/).innerText()).match(/Stable employee #(\d+) · Period #(\d+)/)!
    if (kind === 'manager') {
      await profile.getByRole('button', { name: 'Change classification', exact: true }).click()
      const dialog = page.getByRole('dialog')
      await dialog.getByLabel('Employment classification').selectOption('business_manager')
      await dialog.getByRole('checkbox', { name: /I confirm/ }).check()
      await dialog.getByRole('button', { name: 'Save changes' }).click()
      await expect(dialog).toHaveCount(0)
    }
    await profile.getByRole('button', { name: 'Terminate employee', exact: true }).click()
    let dialog = page.getByRole('dialog')
    await expect(dialog.getByText(/Unassign future jobs and cancel future shifts/)).toBeVisible()
    await expect(dialog.getByText(/Retain complete employment/)).toBeVisible()
    await dialog.getByRole('checkbox', { name: /I confirm employment termination/ }).check()
    await page.setViewportSize({ width: 390, height: 844 })
    await dialog.getByRole('button', { name: 'Save changes' }).focus()
    await page.keyboard.press('Enter')
    await expect(profile.getByText(/Historical \/ former period/)).toBeVisible()
    await expect(admin.employees.getByRole('button', { name: 'Former Employees', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await admin.employees.getByRole('button', { name: 'Active Employees', exact: true }).click()
    await expect(admin.employees.getByRole('list', { name: 'Employees', exact: true }).getByRole('heading', { name, exact: true })).toHaveCount(0)
    await admin.employees.getByRole('button', { name: 'Former Employees', exact: true }).click()
    await admin.employees.getByRole('button', { name: `Rehire ${name}`, exact: true }).click()
    dialog = page.getByRole('dialog')
    await expect(dialog.getByText(/It restores no business memberships/)).toBeVisible()
    const start = dialog.getByLabel('Rehire start date')
    const minimum = (await start.getAttribute('min'))!
    const previous = new Date(`${minimum}T00:00:00Z`)
    previous.setUTCDate(previous.getUTCDate() - 1)
    await start.fill(previous.toISOString().slice(0, 10))
    await dialog.getByRole('checkbox', { name: /I confirm a new employment period/ }).check()
    await dialog.getByRole('button', { name: 'Save changes' }).click()
    expect(await start.evaluate(el => (el as HTMLInputElement).validity.rangeUnderflow)).toBe(true)
    await start.fill(minimum)
    await dialog.getByRole('button', { name: 'Save changes' }).click()
    await expect(dialog).toHaveCount(0)
    await expect(profile.getByText(/A new employment period was created/)).toBeVisible()
    const after = (await profile.getByText(/Stable employee #/).innerText()).match(/Stable employee #(\d+) · Period #(\d+)/)!
    expect(after[1]).toBe(before[1]); expect(after[2]).not.toBe(before[2])
    await expect(profile.getByText('Updated fixture address', { exact: true })).toHaveCount(0)
    await expect(profile.getByText('Shop assignments: None recorded', { exact: true })).toBeVisible()
    await expect(profile.getByText(/Termination recorded/)).toBeVisible()
    await expect(profile.getByText(/Rehire period/)).toBeVisible()
    await admin.logout()
  })
}
