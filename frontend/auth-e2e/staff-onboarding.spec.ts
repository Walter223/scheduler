import {readFileSync,mkdirSync} from 'node:fs'
import {test,expect} from '@playwright/test'
import {AdminPage} from './pages/AdminPage'
const file=process.env.BFF_E2E_FIXTURE
if(!file)throw Error('Use isolated runner')
const {users}=JSON.parse(readFileSync(file,'utf8')) as {users:{kind:string;username:string;password:string}[]}
test('real Owner proposes multi-shop management without granting access, validates and resumes staff',async({page})=>{
  const admin=new AdminPage(page);await admin.login(users.find(u=>u.kind==='owner')!)
  await page.getByRole('link',{name:'Resume Setup'}).click()
  const setup=page.getByRole('region',{name:'Business setup'})
  await expect(setup.getByText('Saved setup loaded.')).toBeVisible()
  await setup.getByRole('button',{name:'Staff',exact:true}).click()
  await setup.getByRole('button',{name:'Add proposed employee'}).click()
  const person=setup.getByRole('group',{name:'Staff proposal 1',exact:true})
  await person.getByLabel('Full name',{exact:true}).fill('Fictional Manager')
  await person.getByLabel('Work email').fill('manager@example.invalid')
  await person.getByRole('combobox',{name:'Employment classification'}).selectOption('shop_manager')
  const assignments=person.getByRole('group',{name:'Proposed shop assignments',exact:true})
  await assignments.getByRole('checkbox',{name:'Acceptance a shop 1',exact:true}).check();await assignments.getByRole('checkbox',{name:'Mobile preview',exact:true}).check()
  await person.getByLabel('Business-wide HR / finance responsibility').check()
  await person.getByLabel('Request business manager access').check()
  const shopRequest=person.getByLabel('Request shop manager access')
  await expect(shopRequest).not.toBeChecked()
  await shopRequest.focus();await page.keyboard.press('Space')
  await person.getByRole('group',{name:'shop manager',exact:true}).getByRole('group',{name:'Requested access shops',exact:true}).getByRole('checkbox',{name:'Mobile preview',exact:true}).check()
  await person.getByRole('group',{name:'Shop management responsibility',exact:true}).getByRole('checkbox',{name:'Mobile preview',exact:true}).check()
  await setup.getByRole('button',{name:'Save draft',exact:true}).click()
  await expect(setup.getByRole('status')).toHaveText('Saved to this business.')
  await setup.getByRole('button',{name:'Add proposed employee'}).click()
  const duplicate=setup.getByRole('group',{name:'Staff proposal 2',exact:true})
  await duplicate.getByLabel('Full name',{exact:true}).fill('Other fictional staff')
  await duplicate.getByLabel('Work email').fill('MANAGER@example.invalid')
  await duplicate.getByRole('combobox',{name:'Employment classification'}).selectOption('detailer')
  await setup.getByRole('button',{name:'Save draft',exact:true}).click()
  await expect(setup.getByRole('status')).toContainText('not saved')
  mkdirSync('/private/tmp/magnum-staff-onboarding',{recursive:true})
  await setup.screenshot({path:'/private/tmp/magnum-staff-onboarding/validation.png'})
  await duplicate.getByRole('button',{name:'Remove proposed employee Other fictional staff'}).click()
  await setup.getByRole('button',{name:'Save draft',exact:true}).click()
  await expect(setup.getByRole('status')).toHaveText('Saved to this business.')
  for(const width of [1440,1024,768,390,320]){await page.setViewportSize({width,height:1000});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);await setup.screenshot({path:`/private/tmp/magnum-staff-onboarding/staff-${width}.png`})}
  await page.reload();await setup.getByRole('button',{name:'Staff',exact:true}).click()
  await expect(person.getByLabel('Work email')).toHaveValue('manager@example.invalid')
  const refresh=page.waitForResponse(response=>response.url().endsWith('/api/admin/context'))
  await page.evaluate(()=>window.dispatchEvent(new Event('focus')))
  await refresh
  await expect(person.getByLabel('Full name',{exact:true})).toHaveValue('Fictional Manager')
  await setup.getByRole('button',{name:'Review',exact:true}).click()
  await setup.screenshot({path:'/private/tmp/magnum-staff-onboarding/review-320.png'})
  await page.setViewportSize({width:1440,height:1000})
  await setup.screenshot({path:'/private/tmp/magnum-staff-onboarding/review-1440.png'})
  await admin.logout()
})
