import {readFileSync,mkdirSync} from 'node:fs'
import {join} from 'node:path'
import {homedir} from 'node:os'
import {test,expect} from '@playwright/test'
import {AdminPage} from './pages/AdminPage'
const {users}=JSON.parse(readFileSync(process.env.BFF_E2E_FIXTURE!,'utf8'))
test('persisted wizard progresses, skips empty team, resumes and finishes an unpublished review',async({page})=>{
 const admin=new AdminPage(page)
 await admin.login(users.find((u:{kind:string})=>u.kind==='multi_owner'))
 await expect(page.getByRole('link',{name:'Resume Setup',exact:true})).toBeVisible()
 await admin.business.selectOption({label:'Acceptance b'})
 await page.getByRole('link',{name:'Resume Setup',exact:true}).click()
 await page.getByRole('button',{name:'Begin setup',exact:true}).click()
 const setup=page.getByRole('region',{name:'Business setup'})
 const root=process.env.MAGNUM_SCREENSHOT_ARCHIVE || (!process.env.CI ? join(homedir(),'projects','Magnum-Screenshots') : test.info().outputDir)
 const folder=join(root,'ux-b1-progress-bar',new Date().toISOString().replaceAll(':','-'))
 mkdirSync(folder,{recursive:true})
 async function capture(state:string,percent:number){
  await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow',String(percent))
  for(const width of [1440,768,390]){
   await page.setViewportSize({width,height:1000})
   expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
   await page.screenshot({path:join(folder,`${state}-${width}-full.png`),fullPage:true})
   await page.getByRole('progressbar').scrollIntoViewIfNeeded()
   await page.screenshot({path:join(folder,`${state}-${width}-viewport.png`)})
  }
 }
 await capture('provisioning-complete',17)
 await setup.getByRole('button',{name:'Save and continue',exact:true}).click()
 await capture('locations',17)
 await setup.getByLabel('Shop address',{exact:true}).fill('100 Fictional Way')
 await setup.getByRole('button',{name:'Save and continue',exact:true}).click()
 await capture('staff-optional',33)
 await setup.getByRole('button',{name:'Continue without a team',exact:true}).click()
 await capture('services-team-skipped',50)
 await expect(setup.getByText('Skipped · no team planned')).toBeVisible()
 await setup.getByRole('button',{name:'Back',exact:true}).click()
 await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow','50')
 await page.reload()
 await expect(setup.getByRole('button',{name:'Services',exact:true})).toHaveAttribute('aria-current','step')
 await setup.getByRole('button',{name:'Add vehicle category',exact:true}).click()
 await setup.getByLabel('Category 1 name').fill('Custom car')
 await setup.getByRole('button',{name:'Use exterior-care suggestion',exact:true}).click()
 await setup.getByRole('group',{name:'Proposed shop availability',exact:true}).getByLabel('Acceptance b shop 1',{exact:true}).check()
 await setup.getByLabel('Custom car price (USD)',{exact:true}).fill('125.00')
 await setup.getByRole('button',{name:'Save and continue',exact:true}).click()
 await capture('branding',67)
 for(const [label,value] of Object.entries({'Business display name':'Fictional Studio','Public contact email':'hello@example.invalid','Public contact phone':'+1 555 010 1234','Primary color':'#173348','Secondary color':'#eff4f8','Accent color':'#755230'}))await setup.getByLabel(label,{exact:true}).fill(value)
 await setup.getByLabel('Website style preset').selectOption('modern')
 await setup.getByRole('button',{name:'Save and continue',exact:true}).click()
 await capture('review',83)
 await setup.getByRole('button',{name:'Business',exact:true}).focus();await page.keyboard.press('Enter')
 await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow','83')
 await setup.getByRole('button',{name:'Review',exact:true}).click()
 await setup.getByRole('button',{name:'Confirm draft review',exact:true}).click()
 await capture('review-confirmed',83)
 await setup.getByRole('button',{name:'Finish setup review',exact:true}).click()
 await capture('completed-unpublished',100)
 await page.reload();await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow','100')
 await expect(page.getByText('Setup review is saved. Your website is not published.')).toBeVisible()
 await admin.logout()
})
