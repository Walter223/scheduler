test('refresh clears stale private context when permission has been revoked', async () => {
  const fetcher = vi.fn(async (url: string) => Response.json(url === '/api/me'
    ? { authenticated: true, user: { id: 1, email: 'staff@example.invalid' }, csrf_token: 'test' }
    : { businesses: [{ id: 1, name: 'Private business', capabilities: ['dashboard', 'employees'], all_shops: [], shops: [] }] }))
  vi.stubGlobal('fetch', fetcher)
  render(<AdminPage />)
  await screen.findByRole('button', { name: 'Employees and HR' })
  fetcher.mockImplementation(async () => Response.json({ error: 'forbidden' }, { status: 403 }))
  fireEvent.click(screen.getByRole('button', { name: 'Refresh access' }))
  await screen.findByText(/Access is unavailable/)
  expect(screen.queryByText('Private business')).toBeNull()
  expect(screen.queryByRole('button', { name: 'Employees and HR' })).toBeNull()
})

const contexts = [1,2].map(id => ({ id, name: `Business ${id}`, capabilities: ['dashboard','employees','settings'], all_shops: ['appointments'], shops: [shop(id*10),shop(id*10+1)] }))
test('repeated focus keeps business, shop, section and mounted feature state; explicit switching clears it', async () => {
  mount(contexts)
  await screen.findByRole('button', { name: 'Employees and HR' })
  fireEvent.change(screen.getByLabelText('Business'), { target: { value: '2' } })
  fireEvent.change(screen.getByLabelText('Shop'), { target: { value: '21' } })
  fireEvent.click(screen.getByRole('button', { name: 'Employees and HR' }))
  const input = screen.getByLabelText('Retained employee search') as HTMLInputElement
  fireEvent.change(input, { target: { value: 'private search' } })
  for (let i=0; i<3; i++) {
    fireEvent.blur(window)
    fireEvent.focus(window)
    await waitFor(() => expect(screen.queryByText('Checking authorized workspaces…')).toBeNull())
    expect((screen.getByLabelText('Business') as HTMLSelectElement).value).toBe('2')
    expect((screen.getByLabelText('Shop') as HTMLSelectElement).value).toBe('21')
    expect(screen.getByLabelText('Retained employee search')).toBe(input)
    expect(input.value).toBe('private search')
  }
  fireEvent.change(screen.getByLabelText('Shop'), { target: { value: '20' } })
  expect(screen.queryByLabelText('Retained employee search')).toBeNull()
  fireEvent.click(screen.getByRole('button', { name: 'Employees and HR' }))
  expect((screen.getByLabelText('Retained employee search') as HTMLInputElement).value).toBe('')
})
test('changed permissions remove private feature state and select an authorized fallback', async () => {
  mount(contexts)
  await screen.findByRole('button', { name: 'Employees and HR' })
  fireEvent.click(screen.getByRole('button', { name: 'Employees and HR' }))
  vi.mocked(fetch).mockResolvedValue(Response.json({ businesses: [{...contexts[0], capabilities:['settings'], shops:[], all_shops:[]}] }))
  fireEvent.focus(window)
  await screen.findByRole('heading', { name: 'Business settings' })
  expect(screen.queryByLabelText('Retained employee search')).toBeNull()
  expect(screen.queryByRole('button', { name: 'Employees and HR' })).toBeNull()
})
test('transient refresh failure clears private content; retry safely recovers', async () => {
  mount(contexts)
  await screen.findByRole('button', { name: 'Employees and HR' })
  fireEvent.click(screen.getByRole('button', { name: 'Employees and HR' }))
  vi.mocked(fetch).mockRejectedValue(new Error('offline'))
  fireEvent.focus(window)
  await screen.findByText(/Workspaces are temporarily unavailable/)
  expect(screen.queryByLabelText('Retained employee search')).toBeNull()
  expect(screen.queryByRole('button', { name: 'Employees and HR' })).toBeNull()
  vi.mocked(fetch).mockResolvedValue(Response.json({ businesses: contexts }))
  fireEvent.click(screen.getByRole('button', { name: 'Refresh access' }))
  await screen.findByLabelText('Retained employee search')
})
test('older refresh cannot overwrite the latest revocation response', async () => {
  mount(contexts)
  await screen.findByRole('button', { name: 'Employees and HR' })
  let finish!: (value: Response) => void
  vi.mocked(fetch).mockImplementationOnce(() => new Promise<Response>(r => { finish=r }))
  fireEvent.focus(window)
  vi.mocked(fetch).mockResolvedValue(Response.json({businesses:[]}))
  fireEvent.focus(window)
  await screen.findByText(/No management workspaces/)
  await act(async () => finish(Response.json({businesses:contexts})))
  expect(screen.queryByRole('button', { name: 'Employees and HR' })).toBeNull()
})
