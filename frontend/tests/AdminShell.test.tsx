test('revoked selected shop clears the old calendar and chooses only a permitted shop', async () => {
  mount(contexts)
  await screen.findByRole('button', { name: 'Appointments and calendar' })
  fireEvent.change(screen.getByLabelText('Shop'), { target:{ value:'11' } })
  fireEvent.click(screen.getByRole('button', { name:'Appointments and calendar' }))
  const input = screen.getByLabelText('Retained calendar date')
  fireEvent.change(input, { target:{value:'2026-12-20'} })
  fireEvent.focus(window)
  await waitFor(() => expect(screen.queryByText('Checking authorized workspaces…')).toBeNull())
  expect(screen.getByLabelText('Retained calendar date')).toBe(input)
  vi.mocked(fetch).mockResolvedValue(Response.json({businesses:[{...contexts[0], shops:[shop(10)], all_shops:[]}]}))
  fireEvent.focus(window)
  await waitFor(() => expect((screen.getByLabelText('Shop') as HTMLSelectElement).value).toBe('10'))
  expect(screen.queryByLabelText('Retained calendar date')).toBeNull()
})

