import { afterEach, expect, test, vi } from 'vitest'
import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import EmployeeDirectory from '../src/components/EmployeeDirectory'
afterEach(cleanup)
const employee = (period = 30, status = 'active') => ({ employee_id: 10, period_id: period, first_name: 'Taylor', last_name: 'Worker', classification: 'detailer', status, starts_on: period === 10 ? '2025-01-01' : '2026-01-01', ends_on: status === 'ended' ? '2025-12-31' : null, phone: '303-555-0100', email: 'fixture@example.invalid', home_address: 'Fixture address', shops: [{ id: 1, name: 'Shop A', status: 'active', starts_on: '2026-01-01', ends_on: null }], salary: 'SECRET_PAY', user_id: 'PRIVATE_ID' })
const page = (items = [employee()], cursor: string | null = null) => ({ employees: items, meta: { has_more: cursor !== null, next_cursor: cursor } })
test('HR current/former directory, server-side name/classification filters and bounded pagination', async () => {
  const fetcher = vi.fn(async (url: string) => Response.json(page([employee()], url.includes('cursor=') ? null : 'owned-cursor')))
  vi.stubGlobal('fetch', fetcher)
  render(<EmployeeDirectory businessId={1} shopId={0} hr />)
  await screen.findByRole('heading', { name: 'Taylor Worker' })
  expect(document.body.textContent).not.toContain('SECRET_PAY')
  expect(document.body.textContent).not.toContain('PRIVATE_ID')
  fireEvent.click(screen.getByRole('button', { name: 'Next page' }))
  await waitFor(() => expect(fetcher.mock.calls.at(-1)?.[0]).toContain('cursor=owned-cursor'))
  fireEvent.click(screen.getByRole('button', { name: 'Former Employees' }))
  await waitFor(() => expect(fetcher.mock.calls.at(-1)?.[0]).toContain('status=former'))
  expect(fetcher.mock.calls.at(-1)?.[0]).not.toContain('cursor=')
  fireEvent.change(screen.getByLabelText('Search employee names'), { target: { value: 'Taylor' } })
  fireEvent.click(screen.getByRole('button', { name: 'Search' }))
  await waitFor(() => expect(fetcher.mock.calls.at(-1)?.[0]).toContain('q=Taylor'))
  fireEvent.change(screen.getByLabelText('Classification'), { target: { value: 'detailer' } })
  await waitFor(() => expect(fetcher.mock.calls.at(-1)?.[0]).toContain('classification=detailer'))
})
test('profile and timeline keep stable employee identity separate from rehire period IDs', async () => {
  const fetcher = vi.fn(async (url: string) => Response.json(url.includes('/periods?') ? page([employee(10, 'ended'), employee(30)]) : url.endsWith('/employees/10') ? { employee: employee() } : url.endsWith('/periods/10') ? { employee: employee(10, 'ended') } : page()))
  vi.stubGlobal('fetch', fetcher)
  render(<EmployeeDirectory businessId={1} shopId={1} hr />)
  fireEvent.click(await screen.findByRole('button', { name: 'View profile and history for Taylor Worker' }))
  await screen.findByRole('heading', { name: 'Employment timeline' })
  expect(screen.getByText(/Original employment/)).toBeTruthy()
  expect(screen.getByText(/Rehire period/)).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: 'View period 10' }))
  await screen.findByText(/Historical \/ former period/)
  expect(fetcher.mock.calls.some(([url]) => url.endsWith('/employees/10/periods/10'))).toBe(true)
  expect(fetcher.mock.calls.some(([url]) => url.includes('/employees/30'))).toBe(false)
})
test('Shop Managers use only scoped current roster and never request history', async () => {
  const fetcher = vi.fn(async () => Response.json(page()))
  vi.stubGlobal('fetch', fetcher)
  render(<EmployeeDirectory businessId={1} shopId={2} hr={false} />)
  await screen.findByRole('heading', { name: 'Taylor Worker' })
  expect(fetcher.mock.calls[0]).toBeTruthy()
  expect(screen.queryByRole('button', { name: 'Former Employees' })).toBeNull()
  expect(screen.queryByRole('button', { name: /View profile/ })).toBeNull()
})
test('context replacement aborts old requests and drops late private responses', async () => {
  let resolve!: (response: Response) => void
  vi.stubGlobal('fetch', vi.fn((url: string) => url.includes('/1/employees') ? new Promise<Response>(r => { resolve = r }) : Promise.resolve(Response.json(page([])))))
  const view = render(<EmployeeDirectory key="1" businessId={1} shopId={0} hr />)
  view.rerender(<EmployeeDirectory key="2" businessId={2} shopId={0} hr />)
  await screen.findByText('No employees match this view.')
  await act(async () => resolve(Response.json(page())))
  expect(screen.queryByText('Taylor Worker')).toBeNull()
})
test.each([401, 403, 503])('refresh failure %s removes contact and profile data', async status => {
  const fetcher = vi.fn(async () => Response.json(page()))
  vi.stubGlobal('fetch', fetcher)
  render(<EmployeeDirectory businessId={1} shopId={0} hr />)
  await screen.findByText('Fixture address')
  fetcher.mockImplementation(async () => Response.json({ error: 'denied' }, { status }))
  fireEvent.click(screen.getByRole('button', { name: 'Refresh employees' }))
  await screen.findByRole('alert')
  expect(screen.queryByText('Fixture address')).toBeNull()
})
test('revocation discovered by a profile request clears the whole private directory', async () => {
  vi.stubGlobal('fetch', vi.fn(async (url: string) => url.endsWith('/employees/10') || url.includes('/periods?')
    ? Response.json({ error: 'forbidden' }, { status: 403 }) : Response.json(page())))
  render(<EmployeeDirectory businessId={1} shopId={0} hr />)
  fireEvent.click(await screen.findByRole('button', { name: 'View profile and history for Taylor Worker' }))
  await screen.findByRole('alert')
  expect(screen.queryByText('Fixture address')).toBeNull()
  expect(screen.queryByRole('heading', { name: 'Taylor Worker' })).toBeNull()
})
